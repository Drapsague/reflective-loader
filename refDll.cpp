void rox(char* d, size_t d_len, char* k, size_t k_len) {
        int j;

        j = 0;
        for (int i = 0; i < d_len; i++) {
                if (j == k_len - 1)
                        j = 0;

                d[i] = d[i] ^ k[j];
                j++;
        }
}

